import assert from 'node:assert/strict';
import { reconcileWork, calculateActualPayroll, projectLabor } from './labor-engine.js';
const member={id:'m',hourly_rate:12000,contract:'3.3',night_pay:false,labor_law:false};
const punch=(id,kind,at)=>({id,kind,at,member_id:'m',store_id:'s'});
const a=[punch(1,'in','2026-10-13T09:00:00Z'),punch(2,'out','2026-10-13T13:00:00Z')];
let r=reconcileWork({memberId:'m',storeId:'s',attendance:a,manualRecords:[]});
assert.equal(r.confirmed.length,1);
assert.equal(r.confirmed[0].work_date,'2026-10-13');
assert.equal(reconcileWork({memberId:'m',storeId:'other',attendance:a,manualRecords:[]}).confirmed.length,0);
assert.equal(reconcileWork({memberId:'m',storeId:'s',attendance:[a[0]],manualRecords:[]}).open.length,1);
const manual={id:'manual',member_id:'m',store_id:'s',work_date:'2026-10-13',start_at:a[0].at,end_at:a[1].at,break_min:30,source:'manual',status:'confirmed'};
r=reconcileWork({memberId:'m',storeId:'s',attendance:a,manualRecords:[manual]});
assert.equal(r.conflicts.length,2);assert.equal(r.confirmed.length,0);
r=reconcileWork({memberId:'m',storeId:'s',attendance:[...a,...a],manualRecords:[]});assert.equal(r.confirmed.length,1);
const result=calculateActualPayroll({member,records:[manual],period:'2026-10',nightWindow:['22:00','06:00']});
assert.equal(result.gross,42000);assert.equal(result.hours,3.5);assert.equal(result.ded,1380);
assert.equal(calculateActualPayroll({member:{...member,contract:'4대'},records:[{...manual,pay_snapshot:{contract:'3.3'}}],period:'2026-10'}).ded,1380,'recorded contract protects historical deductions');
assert.equal(calculateActualPayroll({member,records:[{...manual,pay_basis:'daily',base_rate:120000}],period:'2026-10'}).gross,120000);
assert.equal(calculateActualPayroll({member,records:[{...manual,end_at:null,status:'open'}],period:'2026-10'}).gross,0);
assert.throws(()=>calculateActualPayroll({member,records:[{...manual,break_min:500}],period:'2026-10'}));
assert.equal(projectLabor({actual:[{...manual,gross:42000}],scheduled:[{...manual,gross:50000}],actualFrom:'2026-10-01',period:'2026-10'}).projectedGross,42000);
console.log('Labor engine: QR pairing, incomplete, overlap, scope, fixed daily pay, breaks, tax and projection passed');
