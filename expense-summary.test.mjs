import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import * as E from './engine.js';
const src=readFileSync(new URL('./app.js',import.meta.url),'utf8');
const c={E,now:new Date(2026,9,15),TODAY:'2026-10-15',S:{y:2026,m:10,store:{equip:{card_rate:1.6}},hist:[{report_date:'2026-10-15',sales:10000000,card:1000000}],expAll:[{spent_on:'2026-10-10',category:'goods',amount:500000},{spent_on:'2026-10-15',category:'etc',amount:200000},{spent_on:'2026-10-20',category:'goods',amount:900000}],posts:[],expenses:[]},monthRange:()=>['2026-10-01','2026-10-31'],fixedFor:()=>({fx:{rent:3100000},own:true}),laborOf:(_y,_m,actual)=>actual?1000000:3100000,isOwner:()=>true,esc:String,man:String};
c.S.expenses=c.S.expAll;
vm.createContext(c);
vm.runInContext(src.slice(src.indexOf('const CAT ='),src.indexOf('const SLOT =')),c);
vm.runInContext(src.slice(src.indexOf('const FIXED ='),src.indexOf('const monKey =')),c);
vm.runInContext(src.slice(src.indexOf('function monthSummary('),src.indexOf('// ===== 보안')),c);
vm.runInContext(src.slice(src.indexOf('function expenseCategories('),src.indexOf('function fixedYearSheet(')),c);
const result=c.monthSummary(2026,10);
assert.equal(result.earned,6784000,'deduct incurred labor, full dated expenses, elapsed fixed cost and actual card fees');
let html=c.fixedCard();
assert.ok(html.includes('₩16,000'), 'card fees fallback is visible in expense totals');
assert.ok(html.includes('음료·소모품')&&html.includes('기타'),'all expense categories appear');
assert.ok(html.includes('14.0%'),'monthly goods / actual monthly sales');
assert.ok(html.includes('2.0%'),'miscellaneous / actual monthly sales');
c.S.hist=[];
html=c.fixedCard();
assert.ok(!html.includes('NaN')&&!html.includes('Infinity'));
assert.ok(html.includes('매출 대비 —'),'zero sales have no percentage');
c.S.hist=[{report_date:'2026-10-15',sales:10000000,card:1000000}];
c.S.expAll.push({spent_on:'2026-10-10',category:'rent',amount:3100000},{spent_on:'2026-10-10',category:'card',amount:20000});
assert.equal(c.monthSummary(2026,10).earned,5180000,'explicit rent and card entries replace estimates without double counting');
console.log('Expense summary: categories, sales ratios, full incurred costs, future exclusion and fixed/card overrides passed');

const payrollContext={S:{store:{id:'store'},members:[]},E,erpUI:{periodPayroll:()=>({members:[{gross:120000,projected_gross:300000}]})}};
vm.createContext(payrollContext);
vm.runInContext(src.slice(src.indexOf('const laborOf='),src.indexOf('function dailyLaborCard('))+';globalThis.getLabor=laborOf;',payrollContext);
assert.equal(payrollContext.getLabor(2026,10,true),120000,'completed operating payroll is used even before actual-payroll activation');
