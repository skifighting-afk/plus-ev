import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const src=readFileSync(new URL('./app.js',import.meta.url),'utf8');
const c={S:{store:{cfg:{expense_categories:['얼음']}},expAll:[{category:'custom:세탁'}]},TODAY:'2026-10-23',esc:s=>String(s??'').replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('"','&quot;'),openSheet:html=>c.html=html};
vm.createContext(c);
vm.runInContext(src.slice(src.indexOf('const CAT ='),src.indexOf('const SLOT =')),c);
vm.runInContext(src.slice(src.indexOf('function expenseCategories('),src.indexOf('function fixedCard(')),c);
assert.equal(c.categoryName('custom:얼음'),'얼음');
assert.equal(c.expenseCategories()['custom:얼음'],'얼음');
assert.equal(c.expenseCategories()['custom:세탁'],'세탁');
c.expenseForm({id:7,category:'custom:세탁',amount:12300,spent_on:'2026-10-11',memo:'<test>',photo:'keep.jpg',source:'bill'});
assert.ok(c.html.includes('data-id="7"')&&c.html.includes('value="12300"')&&c.html.includes('value="2026-10-11"'));
assert.ok(c.html.includes('value="custom:세탁" selected'));
assert.ok(!c.html.includes('value="<test>"'));
assert.ok(c.html.includes('항목 추가')&&c.html.includes('수정 저장'));
c.expenseForm({id:8,source:'close',category:'goods',amount:100,spent_on:'2026-10-10'});
assert.ok(c.html.includes('readonly'),'closing-linked amounts and dates cannot silently diverge');
console.log('Expense editing: custom categories, persisted selection, existing values, escaping and closing restrictions passed');
