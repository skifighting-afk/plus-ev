import assert from 'node:assert/strict';
globalThis.window = {};
const { createClient } = await import('./demo/mock-sb.js');
const db = window.__DB, client = createClient();
window.__USERS['staff@test.dev'] = {id:'staff',email:'staff@test.dev'};
db.members.push({id:'member',user_id:'staff',store_id:'store',active:true});
await client.auth.signInWithPassword({email:'staff@test.dev'});
const run = kind => client.rpc('attend_selected',{p_code:String(Math.floor(Date.now()/30000)*7919%1000000).padStart(6,'0'),p_kind:kind,p_store:'store'});
assert.ok((await run('out')).error);
assert.equal(db.attendance.length,0);
assert.equal((await run('in')).data,'in');
assert.ok((await run('in')).error);
assert.equal(db.attendance.length,1);
assert.equal((await run('out')).data,'out');
assert.ok((await run('out')).error);
assert.equal(db.attendance.length,2);
db.members.push({id:'member-b',user_id:'staff',store_id:'store-b',active:true});
const code = String(Math.floor(Date.now()/30000)*7919%1000000).padStart(6,'0');
assert.equal((await client.rpc('attend_selected',{p_code:code,p_kind:'in',p_store:'store-b'})).data,'in');
assert.equal(db.attendance.at(-1).member_id,'member-b','selected membership receives the record');
assert.equal(db.attendance.filter(a=>a.member_id==='member').length,2,'other store is unchanged');
assert.ok((await client.rpc('attend_selected',{p_code:code,p_kind:'in',p_store:'unrelated'})).error);
assert.ok((await run('invalid')).error);
assert.equal(db.attendance.length,3);
console.log('selected attendance: explicit in/out and duplicate protection passed');
